test('invalid ownership, unsupported unsplittable giants and impossible page bounds fail before mutation', () => {
  assert.throws(() => planPdfPagination({ pages: [page(0)], blocks: [block(1, 720, 800)] }), /split|line|tall|fit/i);
  assert.throws(() => planPdfPagination({ pages: [page(0)], blocks: [block(1, 720, 20), block(2, 690, 20, { objectIndices: [1] })] }), /owned|duplicate|shared/i);
  const missing = lineParagraph(2, 40); missing.objectIndices.push(999);
  assert.throws(() => planPdfPagination({ pages: [page(0)], blocks: [missing] }), /part|owned|object|line/i);
  assert.throws(() => planPdfPagination({ pages: [page(0, { contentBottom: 730 })], blocks: [] }), /bound|layout/i);
  assert.throws(() => planPdfPagination({ pages: [page(0)], blocks: [block(1, 720, 20, { box: { x: 0, top: 720, w: 700, h: 20 } })] }), /wide|width/i);
});

