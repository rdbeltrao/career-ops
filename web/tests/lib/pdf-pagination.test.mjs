test('fractional font metrics never overflow content bounds or orphan headings across many layouts', () => {
  for (let seed = 0; seed < 250; seed++) {
    let state = seed + 1;
    const random = () => { state = (state * 1664525 + 1013904223) >>> 0; return state / 4294967296; };
    const blocks = Array.from({ length: 30 }, (_, id) => block(id, 730 - id * 28, id % 5 === 0 ? 20 : 20 + random() * 420,
      { kind: id % 5 === 0 ? 'heading' : 'paragraph', gapBefore: random() * 15 }));
    const plan = planPdfPagination({ pages: [page(0, { contentTop: 730, contentBottom: 40 })], blocks });
    assertOwnedOnce(plan, blocks);
    for (const placement of plan.placements) assert.ok(placement.box.top - placement.box.h >= 40 - 1e-6, `Seed ${seed} overflowed`);
    for (let index = 0; index < blocks.length - 1; index++) {
      if (blocks[index].kind === 'heading') assert.equal(plan.placements[index].toPage, plan.placements[index + 1].toPage);
    }
  }
});

