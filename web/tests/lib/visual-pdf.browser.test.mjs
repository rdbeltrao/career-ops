import assert from 'node:assert/strict';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import test from 'node:test';
import { PdfEngine } from '../../public/vendor/bentopdf/core.js';
import { paragraphText } from '../../public/pdf-editor/model.mjs';

const url = process.env.VISUAL_PDF_TEST_URL;
const root = process.env.VISUAL_PDF_TEST_ROOT;

test('Classic and visual editing, AI proposals, safe saves, versions, trash and recovery', { skip: !url || !root, timeout: 180_000 }, async (t) => {
  const origin = new URL(url);
  assert.ok(['localhost','127.0.0.1'].includes(origin.hostname));
  const relative = path.relative(fs.realpathSync(os.tmpdir()), fs.realpathSync(root));
  assert.ok(relative && !relative.startsWith('..') && !path.isAbsolute(relative));
  assert.equal(fs.readFileSync(path.join(root, '.visual-pdf-fixture'), 'utf8').trim(), 'fictional-only');
  const trackerPath = path.join(root, 'data/applications.md');
  const tracker = fs.readFileSync(trackerPath, 'utf8');
  fs.writeFileSync(trackerPath, tracker.replace('| 11 |', '| 27 |'));
  t.after(() => fs.writeFileSync(trackerPath, tracker));
  const { chromium } = await import('playwright-core');
  const browser = await chromium.launch({ channel: 'chrome', headless: true });
  t.after(() => browser.close());
  const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  page.on('dialog', dialog => dialog.accept());
  const original = fs.readFileSync(path.join(root, 'output/cv-fixture-alpha.pdf'));
  t.after(() => fs.writeFileSync(path.join(root, 'output/cv-fixture-alpha.pdf'), original));
  await page.goto(`${origin.origin}/documents`);
  await page.getByRole('link', { name: /Visual PDF editor/ }).waitFor();
  assert.equal(await page.getByRole('link', { name: /Classic editor/ }).getAttribute('href'), '/pipeline/27/cv-studio');
  await page.getByRole('link', { name: /Classic editor/ }).click();
  await page.getByRole('button', { name: 'Save for apply' }).waitFor();
  await page.goto(`${origin.origin}/documents`);
  await page.goto(`${origin.origin}/pipeline/27/cv-visual`);
  await page.getByRole('heading', { name: 'Visual PDF editor', exact: true }).waitFor();
  const frame = page.frameLocator('iframe[title="Editable PDF pages"]');
  const paragraph = text => frame.getByRole('button', { name: `Edit paragraph: ${text}`, exact: true });
  await paragraph('Engineering leader building reliable products.').click();
  const field = page.getByLabel('Paragraph text', { exact: true });
  await field.fill('Engineering leader delivering products.');
  assert.equal(await page.locator('iframe[title="Editable PDF pages"]').getAttribute('inert'), '');
  await page.goBack();
  await page.getByRole('heading', {name:'Documents',exact:true}).waitFor();
  await page.goForward();
  await page.getByText('Recovered your unsaved changes from this device.').waitFor();
  assert.equal(await field.inputValue(),'Engineering leader delivering products.');
  await page.getByRole('button', { name: 'Apply text', exact: true }).click();
  await paragraph('Engineering leader delivering products.').waitFor();
  // Next's programmatic navigation, like the assistant, need not fire beforeunload.
  await page.goBack();
  await page.getByRole('heading', {name:'Documents',exact:true}).waitFor();
  await page.goForward();
  await paragraph('Engineering leader delivering products.').waitFor();
  await page.getByText('Recovered your unsaved changes from this device.').waitFor();
  await page.getByRole('button', { name: 'Save PDF', exact: true }).click();
  await page.getByText('PDF saved. The previous version is available below.').waitFor();
  const engine = await PdfEngine.create();
  t.after(() => engine.close());
  const pdfText = () => {
    engine.open(new Uint8Array(fs.readFileSync(path.join(root,'output/cv-fixture-alpha.pdf'))));
    return Array.from({length:engine.pageCount}, (_, i) => { engine.loadPage(i); return engine.buildModel().map(paragraphText).join('\n'); }).join('\n');
  };
  assert.match(pdfText(), /Engineering leader delivering products\./);
  assert.doesNotMatch(pdfText(), /Engineering leader building reliable products\./);
  assert.match(pdfText(), /Fictional education entry/);
  await page.reload();
  await paragraph('Engineering leader delivering products.').click();
  await page.evaluate(() => localStorage.setItem('career-ops:config', JSON.stringify({cliId:'codex'})));
  await page.route('**/api/documents/*/rewrite', route => route.fulfill({status:200, contentType:'application/json', body:JSON.stringify({text:'Engineering leader building products.',warning:null})}));
  await page.getByLabel('What should change?').fill('Make it concise.');
  await page.getByRole('button', { name:'Suggest rewrite',exact:true }).click();
  await page.getByRole('button', { name:'Reject',exact:true }).click();
  assert.equal(await paragraph('Engineering leader delivering products.').count(),1);
  await page.getByRole('button', { name:'Suggest rewrite',exact:true }).click();
  await page.getByRole('button', { name:'Use suggestion',exact:true }).click();
  await paragraph('Engineering leader building products.').waitFor();
  await page.getByRole('button', { name:'Save PDF',exact:true }).click();
  await page.getByText('PDF saved. The previous version is available below.').waitFor();
  assert.match(pdfText(), /Engineering leader building products\./);
  await paragraph('Engineering leader building products.').click();
  await page.waitForFunction(() => document.querySelector('#paragraph-text')?.value === 'Engineering leader building products.');
  const editorFrame = page.frames().find(candidate => candidate.url().includes('/pdf-editor/index.html'));
  await editorFrame.evaluate(async () => {
    const { PdfEngine } = await import('/vendor/bentopdf/core.js');
    const original = PdfEngine.prototype.saveSpliced;
    let saves = 0;
    PdfEngine.prototype.saveSpliced = async function (...args) {
      if (++saves === 2) {
        PdfEngine.prototype.saveSpliced = original;
        throw new Error('Injected snapshot failure');
      }
      return original.apply(this, args);
    };
  });
  await field.fill('Engineering leader delivering products.');
  await page.getByRole('button', { name:'Apply text',exact:true }).click();
  await page.getByRole('alert').filter({hasText:'Injected snapshot failure'}).waitFor();
  assert.equal(await field.inputValue(), 'Engineering leader delivering products.');
  assert.equal(await paragraph('Engineering leader building products.').count(), 1);
  await page.goBack();
  await page.goForward();
  await page.getByText('Recovered your unsaved changes from this device.').waitFor();
  assert.equal(await field.inputValue(), 'Engineering leader delivering products.');
  await page.getByRole('button', { name:'Discard text changes',exact:true }).click();
  await field.fill('Additional content that cannot fit on this page. '.repeat(70));
  await page.getByRole('button', { name:'Apply text',exact:true }).click();
  await page.getByRole('alert').waitFor();
  assert.equal(await paragraph('Engineering leader building products.').count(),1);
  await page.getByRole('button', { name:'Discard text changes',exact:true }).click();
  await page.locator('summary').filter({hasText:'Saved versions'}).click();
  await page.getByRole('button',{name:'Restore',exact:true}).first().click();
  await paragraph('Engineering leader delivering products.').waitFor();
  await page.setViewportSize({width:390,height:844});
  const resizedFrame = page.frames().find(candidate => candidate.url().includes('/pdf-editor/index.html'));
  await resizedFrame.waitForFunction(() => [...document.querySelectorAll('.page')].every(page => page.getBoundingClientRect().left >= 0 && page.getBoundingClientRect().right <= innerWidth));
  await page.evaluate(() => window.scrollTo(0, 0));
  await page.screenshot({path:path.join(root,'visual-mobile.png'),fullPage:true});
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1),true);
  await page.setViewportSize({width:1440,height:1000});
  await resizedFrame.waitForFunction(() => document.querySelector('.page')?.getBoundingClientRect().width > 700);
  await page.evaluate(() => window.scrollTo(0, 0));
  await page.screenshot({path:path.join(root,'visual-desktop.png'),fullPage:true});
  await page.goto(`${origin.origin}/documents`);
  await page.getByRole('button',{name:'Move to Trash',exact:true}).click();
  await page.getByText('cv-fixture-alpha.pdf moved to Trash.').waitFor();
  assert.equal(fs.existsSync(path.join(root,'output/cv-fixture-alpha.pdf')),false);
  await page.reload();
  await page.locator('summary').filter({hasText:'Trash'}).click();
  await page.getByRole('button',{name:'Restore PDF',exact:true}).click();
  await page.getByText('cv-fixture-alpha.pdf restored.').waitFor();
  assert.equal(fs.existsSync(path.join(root,'output/cv-fixture-alpha.pdf')),true);
  assert.equal(await page.getByRole('link',{name:/Visual PDF editor/}).count(),1);
  assert.deepEqual(errors,[]);
});
