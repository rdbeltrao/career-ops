import assert from 'node:assert/strict';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import test from 'node:test';
import { PdfEngine } from '../../public/vendor/bentopdf/core.js';
import { paragraphText, readParagraphs } from '../../public/pdf-editor/model.mjs';

const url = process.env.VISUAL_PDF_TEST_URL;
const root = process.env.VISUAL_PDF_TEST_ROOT;

test('direct PDF typing, AI preview, styled recovery and document lifecycle', { skip: !url || !root, timeout: 180_000 }, async t => {
  const origin = new URL(url);
  assert.ok(['localhost', '127.0.0.1'].includes(origin.hostname));
  const relative = path.relative(fs.realpathSync(os.tmpdir()), fs.realpathSync(root));
  assert.ok(relative && !relative.startsWith('..') && !path.isAbsolute(relative));
  assert.equal(fs.readFileSync(path.join(root, '.visual-pdf-fixture'), 'utf8').trim(), 'fictional-only');
  const trackerPath = path.join(root, 'data/applications.md');
  const tracker = fs.readFileSync(trackerPath, 'utf8');
  fs.writeFileSync(trackerPath, tracker.replace('| 11 |', '| 27 |'));
  t.after(() => fs.writeFileSync(trackerPath, tracker));
  const file = path.join(root, 'output/cv-fixture-alpha.pdf');
  const original = fs.readFileSync(file);
  t.after(() => fs.writeFileSync(file, original));
  const { chromium } = await import('playwright-core');
  const browser = await chromium.launch({ channel: 'chrome', headless: true });
  t.after(() => browser.close());
  const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
  page.setDefaultTimeout(15000);
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  page.on('dialog', dialog => dialog.accept());
  const engine = await PdfEngine.create();
  t.after(() => engine.close());
  const savedPages = () => {
    engine.open(new Uint8Array(fs.readFileSync(file)));
    return Array.from({ length: engine.pageCount }, (_, pageIndex) => {
      engine.loadPage(pageIndex);
      return readParagraphs(engine).map(paragraph => ({ text: paragraphText(paragraph), box: paragraph.box }));
    });
  };
  const savedText = () => savedPages().flat().map(paragraph => paragraph.text).join('\n');
  await page.goto(`${origin.origin}/documents`);
  const classic = page.getByRole('link', { name: /Classic editor/ });
  await classic.waitFor();
  assert.equal(await classic.getAttribute('href'), '/pipeline/27/cv-studio');
  await classic.click();
  await page.getByRole('button', { name: 'Save for apply' }).waitFor();
  await page.goto(`${origin.origin}/documents`);
  await page.goto(`${origin.origin}/pipeline/27/cv-visual`);
  await page.getByRole('heading', { name: 'Visual PDF editor', exact: true }).waitFor();
  assert.equal(await page.getByLabel('Paragraph text', { exact: true }).count(), 0);
  const frame = page.frameLocator('iframe[title="Editable PDF pages"]');
  const paragraph = text => frame.getByRole('button', { name: `Edit paragraph: ${text}`, exact: true });
  const inline = () => frame.getByRole('textbox', { name: 'Edit paragraph on page', exact: true });
  await paragraph('Engineering leader building reliable products.').click();
  await inline().fill('Engineering leader delivering products.');
  assert.equal(await page.locator('iframe').getAttribute('inert'), null);
  await page.goBack();
  await page.getByRole('heading', { name: 'Documents', exact: true }).waitFor();
  await page.goForward();
  await page.getByText('Recovered your unsaved changes from this device.').waitFor();
  assert.equal(await inline().innerText(), 'Engineering leader delivering products.');
  const failSave = route => route.request().method() === 'PUT'
    ? route.fulfill({ status: 500, contentType: 'application/json', body: JSON.stringify({ error: 'Fixture save failure' }) })
    : route.continue();
  await page.route('**/api/documents/*', failSave);
  await page.getByRole('button', { name: 'Save PDF', exact: true }).click();
  await page.getByRole('alert').filter({ hasText: 'Fixture save failure' }).waitFor();
  assert.equal(fs.readFileSync(file).equals(original), true);
  await page.unroute('**/api/documents/*', failSave);
  await paragraph('Engineering leader delivering products.').click();
  await inline().press('ControlOrMeta+s');
  await page.getByText('PDF saved. The previous version is available below.').waitFor();
  assert.match(savedText(), /Engineering leader delivering products\./);
  assert.doesNotMatch(savedText(), /Engineering leader building reliable products\./);
  const descriptor = 'Lead engineering across web and mobile products, working with design teams to improve delivery and build reliable services.';
  await paragraph(descriptor).click();
  assert.equal((await inline().innerText()).replace(/\s+/g, ' ').trim(), descriptor);
  assert.equal(await inline().locator('span').evaluateAll(spans => spans.some(span => getComputedStyle(span).fontStyle === 'italic' || (span.dataset.italic === '1' && !!span.dataset.docfont))), true);
  await inline().press('Escape');
  // Moving Education before Work Experience transfers its whole block from
  // page 2, while history restores both pages atomically.
  await frame.locator('#career-next').click();
  const education = frame.getByRole('button', { name: 'Select section: Education', exact: true });
  await education.waitFor();
  const start = await education.boundingBox();
  assert.ok(start);
  await page.mouse.move(start.x + start.width / 2, start.y + start.height / 2);
  await page.mouse.down();
  await page.mouse.move(start.x + start.width / 2 + 20, start.y + start.height / 2 + 10, { steps: 5 });
  const destination = frame.getByRole('button', { name: 'Drop section before work experience', exact: true });
  await destination.waitFor({ state: 'visible' });
  const drop = await destination.boundingBox();
  assert.ok(drop);
  await page.mouse.move(drop.x + drop.width / 2, drop.y + drop.height / 2, { steps: 12 });
  await page.mouse.up();
  await frame.getByText('Whole section moved. Review the page layout before saving.', { exact: true }).waitFor();
  await page.getByRole('button', { name: 'Save PDF', exact: true }).click();
  await page.getByText('PDF saved. The previous version is available below.').waitFor();
  const movedPages = savedPages();
  assert.ok(movedPages[0].some(p => p.text === 'Education'));
  assert.ok(movedPages[0].some(p => p.text === 'Fictional education entry for a browser test.'));
  assert.ok(!movedPages[1].some(p => /Education|Fictional education/.test(p.text)));
  assert.ok(movedPages[0].find(p => p.text === 'Education').box.top > movedPages[0].find(p => p.text === 'Work Experience').box.top);
  await page.getByRole('button', { name: 'Undo', exact: true }).click();
  await education.waitFor();
  await page.getByRole('button', { name: 'Redo', exact: true }).click();
  await frame.locator('#career-prev').click();
  await education.waitFor();
  await page.getByRole('button', { name: 'Undo', exact: true }).click();
  await page.getByRole('button', { name: 'Save PDF', exact: true }).click();
  await page.getByText('PDF saved. The previous version is available below.').waitFor();
  assert.ok(savedPages()[1].some(p => p.text === 'Education'));
  await frame.getByRole('button', { name: 'Select section: Professional Summary', exact: true }).click();
  await page.evaluate(() => localStorage.setItem('career-ops:config', JSON.stringify({ cliId: 'codex' })));
  await page.route('**/api/documents/*/rewrite', route => {
    const body = route.request().postDataJSON();
    assert.equal(body.targets.length, 2);
    assert.equal(body.targets[0].text, 'Professional Summary');
    return route.fulfill({ status: 200, contentType: 'application/json', body: JSON.stringify({ replacements: body.targets.map(target => ({ paragraphId: target.paragraphId, text: target.text.replace('delivering', 'building') })), warning: null }) });
  });
  await page.getByLabel('What should change?').fill('Make the wording concise.');
  await page.getByRole('button', { name: 'Preview with AI', exact: true }).click();
  await page.getByRole('button', { name: 'Reject', exact: true }).waitFor();
  const preview = frame.getByRole('img', { name: 'AI preview: Engineering leader building products.', exact: true });
  await preview.waitFor();
  await frame.locator('#pageWrap').click({ position: { x: 5, y: 5 }, force: true });
  await preview.waitFor();
  assert.match(savedText(), /Engineering leader delivering products\./);
  assert.equal(await page.getByRole('button', { name: 'Save PDF', exact: true }).isDisabled(), true);
  await page.getByRole('button', { name: 'Reject', exact: true }).click();
  await paragraph('Engineering leader delivering products.').waitFor();
  await page.getByRole('button', { name: 'Preview with AI', exact: true }).click();
  await page.getByRole('button', { name: 'Accept changes', exact: true }).click();
  await page.getByRole('button', { name: 'Save PDF', exact: true }).click();
  await page.getByText('PDF saved. The previous version is available below.').waitFor();
  assert.match(savedText(), /Engineering leader building products\./);
  await page.setViewportSize({ width: 390, height: 844 });
  await page.evaluate(() => window.scrollTo(0, 0));
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1), true);
  await page.waitForFunction(() => {
    const doc = document.querySelector('iframe')?.contentDocument;
    const canvas = doc?.getElementById('pageWrap');
    return canvas && canvas.getBoundingClientRect().width <= doc.documentElement.clientWidth + 1;
  });
  await page.screenshot({ path: path.join(root, 'direct-mobile.png'), fullPage: true });
  await page.setViewportSize({ width: 1440, height: 1000 });
  await page.waitForFunction(() => document.querySelector('iframe')?.contentDocument?.getElementById('pageWrap')?.getBoundingClientRect().width > 900);
  await page.screenshot({ path: path.join(root, 'direct-desktop.png'), fullPage: true });
  await page.locator('summary').filter({ hasText: 'Saved versions' }).click();
  await page.getByRole('button', { name: 'Restore', exact: true }).first().click();
  await paragraph('Engineering leader delivering products.').waitFor();
  await page.goto(`${origin.origin}/documents`);
  await page.getByRole('button', { name: 'Move to Trash', exact: true }).click();
  await page.getByText('cv-fixture-alpha.pdf moved to Trash.').waitFor();
  assert.equal(fs.existsSync(file), false);
  await page.reload();
  await page.locator('summary').filter({ hasText: 'Trash' }).click();
  await page.getByRole('button', { name: 'Restore PDF', exact: true }).click();
  await page.getByText('cv-fixture-alpha.pdf restored.').waitFor();
  assert.equal(fs.existsSync(file), true);
  assert.deepEqual(errors, []);
});
